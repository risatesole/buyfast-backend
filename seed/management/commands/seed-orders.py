import random
from datetime import timedelta

from django.core.management.base import BaseCommand
from django.db import transaction
from django.utils import timezone

from accounts.models import User
from orders.models import Order, OrderItem, OrderPayment
from payment.models import PaymentProvider, PaymentProviderTransaction
from products.default.models import ProductVariant

DEFAULT_USER_COUNT = 50
DEFAULT_MIN_ORDERS = 5
DEFAULT_MAX_ORDERS = 10
DEFAULT_DAYS_BACK = 14

CUSTOMER_PASSWORD = "Customer@12345"
EMAIL_DOMAIN = "buyfast-demo.com"

# Only statuses that make sense alongside a recorded OrderPayment below —
# AWAITING_PAYMENT/CANCELLED orders wouldn't have a completed payment, so
# those are left out of this demo dataset.
STATUS_CHOICES = [Order.Status.PENDING, Order.Status.FULFILLED, Order.Status.RETURNED]

MIN_ITEMS_PER_ORDER = 1
MAX_ITEMS_PER_ORDER = 4

# Reused across runs to build deterministic, idempotent emails
# (seed-customer-000@..., seed-customer-001@..., ...) so re-running the
# command doesn't create duplicate users — it just leaves existing ones
# alone (see get_or_create below) and seeds another batch of orders for them.
FIRST_NAMES = [
    "Carlos", "Maria", "Juan", "Ana", "Luis", "Carmen", "Miguel", "Rosa",
    "Jose", "Laura", "Pedro", "Sofia", "Manuel", "Elena", "Rafael", "Patricia",
    "Diego", "Gabriela", "Fernando", "Valentina", "Ricardo", "Camila", "Alberto",
    "Isabel", "Francisco", "Daniela", "Eduardo", "Andrea", "Roberto", "Lucia",
]

LAST_NAMES = [
    "Perez", "Gonzalez", "Rodriguez", "Fernandez", "Lopez", "Martinez",
    "Sanchez", "Ramirez", "Torres", "Flores", "Rivera", "Gomez", "Diaz",
    "Reyes", "Morales", "Cruz", "Ortiz", "Gutierrez", "Chavez", "Ramos",
    "Vargas", "Castillo", "Jimenez", "Mendoza", "Rojas", "Herrera", "Medina",
]


class Command(BaseCommand):
    help = "Seed demo customers with random orders placed over the last N days"

    def add_arguments(self, parser):
        parser.add_argument(
            "--users",
            type=int,
            default=DEFAULT_USER_COUNT,
            help=f"Number of customers to create (default: {DEFAULT_USER_COUNT})",
        )
        parser.add_argument(
            "--min-orders",
            type=int,
            default=DEFAULT_MIN_ORDERS,
            help=f"Minimum orders per customer (default: {DEFAULT_MIN_ORDERS})",
        )
        parser.add_argument(
            "--max-orders",
            type=int,
            default=DEFAULT_MAX_ORDERS,
            help=f"Maximum orders per customer (default: {DEFAULT_MAX_ORDERS})",
        )
        parser.add_argument(
            "--days",
            type=int,
            default=DEFAULT_DAYS_BACK,
            help=f"Spread order dates over the last N days (default: {DEFAULT_DAYS_BACK})",
        )

    @transaction.atomic
    def handle(self, *args, **options):
        user_count = options["users"]
        min_orders = options["min_orders"]
        max_orders = options["max_orders"]
        days_back = options["days"]

        variants = list(ProductVariant.objects.all())
        if not variants:
            self.stdout.write(
                self.style.ERROR(
                    "  No ProductVariant records found. Run `seed` first to create demo products."
                )
            )
            return

        self.stdout.write(self.style.WARNING(f"\n=== Seeding {user_count} Demo Customers with Orders ===\n"))

        payment_provider, provider_created = PaymentProvider.objects.get_or_create(
            name="Cash / Default Provider",
            defaults={
                "description": "Default payment provider generated by the order seed command.",
                "is_default": True,
            },
        )
        self.stdout.write(f"  PaymentProvider — {'created' if provider_created else 'already exists'}: {payment_provider.name}")

        now = timezone.now()
        users_created = 0
        orders_created = 0
        items_created = 0

        for i in range(user_count):
            first_name = random.choice(FIRST_NAMES)
            last_name = random.choice(LAST_NAMES)
            email = f"seed-customer-{i:03d}@{EMAIL_DOMAIN}"

            user, user_created = User.objects.get_or_create(
                email=email,
                defaults={
                    "first_name": first_name,
                    "last_name": last_name,
                    "role": "customer",
                    "status": "active",
                    "is_email_verified": True,
                    "institution_member": True,
                    "phone_number": f"+1{random.randint(200, 999)}{random.randint(100, 999)}{random.randint(1000, 9999)}",
                },
            )
            if user_created:
                user.set_password(CUSTOMER_PASSWORD)
                user.save()
                users_created += 1

            order_count = random.randint(min_orders, max_orders)
            for _ in range(order_count):
                created_at_offset = timedelta(
                    days=random.randint(0, days_back),
                    hours=random.randint(0, 23),
                    minutes=random.randint(0, 59),
                )
                order_created_at = now - created_at_offset
                status = random.choice(STATUS_CHOICES)
                has_pickup = random.random() > 0.25
                pickup_time = (order_created_at + timedelta(days=random.randint(1, 7))) if has_pickup else None

                order = Order.objects.create(customer=user, status=status, pickup_time=pickup_time)
                Order.objects.filter(pk=order.pk).update(created_at=order_created_at)
                orders_created += 1

                item_count = random.randint(MIN_ITEMS_PER_ORDER, MAX_ITEMS_PER_ORDER)
                chosen_variants = random.sample(variants, k=min(item_count, len(variants)))
                order_subtotal = 0.0
                for variant in chosen_variants:
                    quantity = random.randint(1, 5)
                    price_per_item = float(variant.selling_price)
                    tax_amount = round(price_per_item * float(variant.tax_rate), 2)
                    OrderItem.objects.create(
                        order=order,
                        product=variant,
                        quantity=quantity,
                        price_per_item=price_per_item,
                        tax_amount=tax_amount,
                    )
                    order_subtotal += (price_per_item + tax_amount) * quantity
                    items_created += 1

                payment_transaction = PaymentProviderTransaction.objects.create(
                    payment_provider=payment_provider,
                    reference_document=f"SEED-TXN-{order.id}-{random.randint(1000, 9999)}",
                    amount=round(order_subtotal, 2),
                    tax=0,
                )
                OrderPayment.objects.create(
                    order=order,
                    payment_provider=payment_provider,
                    payment_provider_transaction=payment_transaction,
                    amount=round(order_subtotal, 2),
                    tax_amount=0,
                )

            self.stdout.write(f"  {user.email} — {order_count} orders ({'new user' if user_created else 'existing user'})")

        self.stdout.write(self.style.SUCCESS(
            f"\n✓ Done. {users_created} customers created, {orders_created} orders created, {items_created} order items created.\n"
        ))
        self.stdout.write(f"  Login password for all seeded customers: {CUSTOMER_PASSWORD}\n")
